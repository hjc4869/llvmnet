#!/usr/bin/env bash
# tags: core toolchain
# TC-01: the option tables of docs/user/driver.md are generated from the driver's option table. Fails and regenerates
# the page when it is out of date; review and commit the result.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
mkdir -p "$test_output"
page="$root/docs/user/driver.md"
"$llvmnet" --print-driver-reference >"$test_output/reference.md"
# The generated part sits between the two marker lines; the prose around it is written by hand.
awk -v generated="$test_output/reference.md" '
    /^<!-- generated by llvmnet --print-driver-reference; do not edit -->$/ { print; while ((getline line < generated) > 0) print line; skipping = 1; next }
    /^<!-- end of the generated part -->$/ { skipping = 0 }
    !skipping { print }
' "$page" >"$test_output/driver.md"
if ! diff -u "$page" "$test_output/driver.md"; then
    cp "$test_output/driver.md" "$page"
    printf 'FAIL: docs/user/driver.md was out of date; it has been regenerated, review and commit it\n' >&2
    exit 1
fi
"$llvmnet" --help >"$test_output/help.txt"
for group in "Steps and outputs" "Accepted without effect" "Not accepted" "-Wl, and -Xlinker options"; do
    grep -q "^$group:" "$test_output/help.txt"
done
printf 'PASS: docs/user/driver.md matches the option table and --help lists every group\n'
