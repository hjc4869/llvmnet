#!/usr/bin/env python3
"""Write src/LlvmNet.Compiler/FrontendOptions.cs from "clang-22 --help" and "flang-22 --help".

The driver forwards options it does not handle to the frontend. It must know which of them take their value as the
next argument (so the value is never taken for an input file) and which are joined spellings that begin like one of
llvmnet's own short options (so "-object-file-name=x" is not read as "-o bject-file-name=x"). Both lists come from
the frontends' own help output, so an LLVM upgrade regenerates them; tests/driver-options.sh fails when they drift.

Usage: frontend-options.py [--check] [output.cs]
"""
import os
import re
import subprocess
import sys

CLANG = os.environ.get("LLVMNET_CLANG", "clang-22")
FLANG = os.environ.get("LLVMNET_FLANG", "flang-22")


def parse(text):
    """Yields (name, kind) for every option line of a Clang-style --help: kind is separate, joined, joined-and-separate or flag."""
    for line in text.splitlines():
        match = re.match(r"^  (-{1,2}[^\s<]+)(<[^>]*>)?(?:\s+(<[^>]*>))?", line)
        if not match:
            continue
        name, joined, separate = match.groups()
        if name.startswith("--") and not name.endswith("=") and joined is None and separate is None:
            yield name, "flag"
        elif joined is not None and separate is not None:
            yield name, "joined-and-separate"
        elif joined is not None or name.endswith("="):
            yield name, "joined"
        elif separate is not None:
            yield name, "separate"
        else:
            yield name, "flag"


def collect():
    kinds = {}
    for tool in (CLANG, FLANG):
        text = subprocess.run([tool, "--help"], check=True, capture_output=True, text=True).stdout
        for name, kind in parse(text):
            # The same spelling in both frontends keeps the kind that consumes more, so a value is never lost.
            order = ["flag", "joined", "separate", "joined-and-separate"]
            if name not in kinds or order.index(kind) > order.index(kinds[name]):
                kinds[name] = kind
    return kinds


def render(kinds):
    separate = sorted(name for name, kind in kinds.items() if kind == "separate")
    joined = sorted(name for name, kind in kinds.items() if kind == "joined")
    both = sorted(name for name, kind in kinds.items() if kind == "joined-and-separate")
    flags = sorted(name for name, kind in kinds.items() if kind == "flag")
    lines = ["// Generated by scripts/frontend-options.py from \"clang-22 --help\" and \"flang-22 --help\"; do not edit by hand.",
             "// Regenerate after an LLVM upgrade: tests/driver-options.sh fails when this file no longer matches the frontends.",
             "", "namespace LlvmNet;", "", "internal static class FrontendOptions", "{",
             "    /// <summary>Frontend options whose value is the next argument (\"-include file\"); joined spellings are accepted too.</summary>",
             "    internal static readonly string[] Separate =", "    [", *wrap(separate), "    ];", "",
             "    /// <summary>Frontend options whose value is joined to the name (\"-std=c11\", \"-O2\"); matched by longest prefix.</summary>",
             "    internal static readonly string[] Joined =", "    [", *wrap(joined), "    ];", "",
             "    /// <summary>Frontend options with a joined part and a separate value (\"-Xarch_x86_64 -foo\").</summary>",
             "    internal static readonly string[] JoinedAndSeparate =", "    [", *wrap(both), "    ];", "",
             "    /// <summary>Frontend options without a value, listed so that none is mistaken for a joined spelling of a shorter option.</summary>",
             "    internal static readonly string[] Flags =", "    [", *wrap(flags), "    ];", "}", ""]
    return "\n".join(lines)


def wrap(names):
    lines, current = [], "       "
    for name in names:
        piece = f' "{name}",'
        if len(current) + len(piece) > 118:
            lines.append(current)
            current = "       "
        current += piece
    if current.strip():
        lines.append(current)
    return lines


def main():
    check = "--check" in sys.argv
    arguments = [argument for argument in sys.argv[1:] if argument != "--check"]
    output = arguments[0] if arguments else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "LlvmNet.Compiler", "FrontendOptions.cs")
    text = render(collect())
    if check:
        with open(output) as current:
            if current.read() != text:
                print(f"{output} is out of date; run scripts/frontend-options.py", file=sys.stderr)
                return 1
        return 0
    with open(output, "w") as destination:
        destination.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
