#!/usr/bin/env python3
"""Benchmark harness (PF-01): llvmnet's portable mode under the JIT and NativeAOT against native builds of the same
sources, on the benchmark set in tests/perf/benchmarks.tsv, with regression thresholds against tests/perf/baseline.tsv.

Every benchmark is built three ways from the same sources and flags: natively with the system Clang (clang-22),
and with llvmnet in portable mode, run by `dotnet` (JIT) and published as a NativeAOT executable from the same linked
bitcode. The ffmpeg entries use the decode harness of the ffmpeg integration build: native is the system-mode bitcode
compiled by clang-22, JIT and NativeAOT are the portable build. A first run of every engine checks that its output
equals the native output (and warms the file cache); the measured runs then alternate engine order, one process at a
time, and record the median elapsed time, user and system time and peak RSS.

Regressions: the baseline holds each benchmark's median seconds per engine on a reference host. A run first derives
the speed of this host relative to that one, the geometric mean of native/baseline-native over the benchmarks, then
divides every llvmnet time by it. A benchmark regresses when its normalized time exceeds the baseline by more than the
per-benchmark tolerance, and an engine regresses when the geometric mean of those quotients exceeds 1 by more than the
geomean tolerance. A regression must reproduce in a second measurement before it fails the run.

    scripts/benchmark.py                          build, validate, measure, compare; exit 1 on a regression
    scripts/benchmark.py --validate-only          build and check outputs only
    scripts/benchmark.py --only fannkuch,ffmpeg-hevc-4t --engines native,jit --repeats 3
    scripts/benchmark.py --group micro            one group (micro, suite, ffmpeg, startup)
    scripts/benchmark.py --update-baseline        write this run's medians as the new baseline
    scripts/benchmark.py --compare results.tsv    apply the thresholds to an earlier run's results.tsv

Results go to artifacts/bench/<UTC time>/ (or --output): results.tsv, summary.md, metadata.json, logs, builds.
"""

