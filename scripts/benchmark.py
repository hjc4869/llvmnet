def read_results(path):
    lines = [line.split("\t") for line in Path(path).read_text().splitlines() if line and not line.startswith("#")]
    header, rows = lines[0], lines[1:]
    return [dict(zip(header, row)) for row in rows]


def read_baseline(path):
    baseline = {}
    if not path.is_file():
        return baseline
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith("#") or line.startswith("benchmark\t"):
            continue
        name, engine, seconds = line.split("\t")[:3]
        baseline[(name, engine)] = float(seconds)
    return baseline


def write_baseline(path, rows, metadata):
    lines = [
        "# Benchmark baseline (PF-01): median seconds per benchmark and engine on the reference host, written by",
        "# scripts/benchmark.py --update-baseline. Regressions are judged on llvmnet times normalized by this host's",
        "# speed relative to the reference host (the geometric mean of the native times), see scripts/benchmark.py.",
        f"# Host: {metadata['cpu']}, {metadata['cores']} cores; {metadata['dotnet']}; {metadata['clang']}",
        f"# Commit: {metadata['commit']}; written {metadata['date']}",
        "benchmark\tengine\tmedian_s",
    ]
    for row in sorted(rows, key=lambda row: (row["benchmark"], engines_all.index(row["engine"]))):
        lines.append(f"{row['benchmark']}\t{row['engine']}\t{float(row['median_s']):.4f}")
    path.write_text("\n".join(lines) + "\n")


def compare(rows, baseline, tolerance, geomean_tolerance):
    """Applies the thresholds; returns (host factor, per-row verdicts, per-engine geomeans, failure messages)."""
    native = [(float(row["median_s"]), baseline[(row["benchmark"], "native")]) for row in rows
              if row["engine"] == "native" and (row["benchmark"], "native") in baseline
              and row["group"] not in geomean_excluded]
    factor = geomean([current / reference for current, reference in native]) if native else 1.0
    verdicts = {}
    quotients = {}
    failures = []
    for row in rows:
        key = (row["benchmark"], row["engine"])
        if row["engine"] == "native":
            continue
        if key not in baseline:
            verdicts[key] = ("new", None)
            continue
        quotient = float(row["median_s"]) / factor / baseline[key]
        if row["group"] not in geomean_excluded:
            quotients.setdefault(row["engine"], []).append(quotient)
        if quotient > 1 + tolerance:
            verdicts[key] = ("regression", quotient)
            failures.append(f"{row['benchmark']} {row['engine']}: {quotient:.2f}x the baseline (host-normalized)")
        elif quotient < 1 / (1 + tolerance):
            verdicts[key] = ("faster", quotient)
        else:
            verdicts[key] = ("ok", quotient)
    means = {engine: geomean(values) for engine, values in quotients.items()}
    for engine, mean in means.items():
        if mean > 1 + geomean_tolerance:
            failures.append(f"{engine} geometric mean: {mean:.3f}x the baseline (host-normalized)")
    return factor, verdicts, means, failures


def write_summary(path, rows, metadata, comparison, engines):
    factor, verdicts, means, failures = comparison
    by_key = {(row["benchmark"], row["engine"]): row for row in rows}
    names = list(dict.fromkeys(row["benchmark"] for row in rows))
    groups = {row["benchmark"]: row["group"] for row in rows}
    lines = [
        f"# llvmnet benchmarks ({metadata['date']})",
        "",
        f"Host: {metadata['cpu']}, {metadata['cores']} logical cores, {metadata['kernel']}; {metadata['dotnet']}; "
        f"{metadata['clang']}; commit {metadata['commit']}. Median of {metadata['repeats']} runs; seconds are elapsed "
        "time per process, including startup and JIT compilation. Ratio is llvmnet time over native time; "
        "baseline is the host-normalized time over the baseline's (1.00 = unchanged).",
        "",
    ]
    llvmnet_engines = [engine for engine in engines if engine != "native"]
    header = ["Benchmark", "Group"] + (["Native (s)"] if "native" in engines else [])
    for engine in llvmnet_engines:
        label = {"jit": "JIT", "aot": "NativeAOT"}[engine]
        header += [f"{label} (s)", f"{label} ratio", f"{label} vs baseline"]
    lines.append("| " + " | ".join(header) + " |")
    lines.append("| " + " | ".join(["---", "---"] + ["---:"] * (len(header) - 2)) + " |")
    ratios = {engine: [] for engine in llvmnet_engines}
    for name in names:
        cells = [name, groups[name]]
        if "native" in engines:
            native = by_key.get((name, "native"))
            cells.append(f"{float(native['median_s']):.3f}" if native else "")
        for engine in llvmnet_engines:
            row = by_key.get((name, engine))
            if row is None:
                cells += ["", "", ""]
                continue
            ratio = row["ratio_to_native"]
            cells += [f"{float(row['median_s']):.3f}", f"{float(ratio):.2f}" if ratio not in ("", "nan") else ""]
            verdict, quotient = verdicts.get((name, engine), ("", None))
            if quotient is None:
                cells.append("new" if verdict == "new" else "")
            else:
                cells.append({"regression": f"**{quotient:.2f} regression**", "faster": f"{quotient:.2f} faster"}
                             .get(verdict, f"{quotient:.2f}"))
            if ratio not in ("", "nan") and groups[name] not in geomean_excluded:
                ratios[engine].append(float(ratio))
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    for engine in llvmnet_engines:
        label = {"jit": "JIT", "aot": "NativeAOT"}[engine]
        if ratios[engine]:
            text = f"- {label}: geometric mean of the ratios to native {geomean(ratios[engine]):.2f} over {len(ratios[engine])} benchmarks"
            if engine in means:
                text += f"; against the baseline {means[engine]:.3f}"
            lines.append(text + " (startup excluded).")
    lines.append(f"- Host speed relative to the baseline host (native geometric mean): {factor:.3f}.")
    lines.append(f"- Thresholds: a benchmark regresses above {1 + metadata['tolerance']:.2f}x its baseline, "
                 f"an engine's geometric mean above {1 + metadata['geomean_tolerance']:.2f}x.")
    if failures:
        lines += ["", "Regressions:", ""] + [f"- {failure}" for failure in failures]
    path.write_text("\n".join(lines) + "\n")


def metadata_for(arguments):
    def command(*parts):
        try:
            return subprocess.run(parts, capture_output=True, text=True, timeout=60).stdout.strip()
        except OSError:
            return ""
    cpu = ""
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                cpu = line.split(":", 1)[1].strip()
                break
    except OSError:
        cpu = platform.processor()
    runtimes = command("dotnet", "--list-runtimes").splitlines()
    # Programs run on the newest .NET 10 runtime (runtimeconfig.json rolls forward within the band only).
    core = [line.split()[1] for line in runtimes if line.startswith("Microsoft.NETCore.App 10.")]
    return {
        "date": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "cpu": cpu or "unknown CPU",
        "cores": os.cpu_count(),
        "kernel": f"{platform.system()} {platform.release()}",
        "dotnet": f".NET runtime {core[-1] if core else 'unknown'}",
        "clang": (command("clang-22", "--version").splitlines() or ["clang-22 unknown"])[0],
        "commit": command("git", "-C", str(root), "describe", "--always", "--dirty") or "unknown",
        "repeats": arguments.repeats,
        "tolerance": arguments.tolerance,
        "geomean_tolerance": arguments.geomean_tolerance,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", help="comma-separated benchmark names (a name ending in * is a prefix)")
    parser.add_argument("--group", action="append", help="benchmark group to run (repeatable)")
    parser.add_argument("--engines", default=",".join(engines_all), help="comma-separated: native, jit, aot")
    parser.add_argument("--repeats", type=int, default=5, help="measured runs per engine (default 5)")
    parser.add_argument("--jobs", type=int, default=min(8, os.cpu_count() or 1), help="parallel builds")
    parser.add_argument("--timeout", type=int, default=600, help="seconds per process (default 600)")
    parser.add_argument("--output", type=Path, help="output directory (default artifacts/bench/<UTC time>)")
    parser.add_argument("--baseline", type=Path, default=default_baseline)
    parser.add_argument("--tolerance", type=float, default=default_tolerance)
    parser.add_argument("--geomean-tolerance", type=float, default=default_geomean_tolerance)
    parser.add_argument("--validate-only", action="store_true", help="build and check outputs, measure nothing")
    parser.add_argument("--update-baseline", action="store_true", help="write the measured medians to the baseline")
    parser.add_argument("--no-ffmpeg-build", action="store_true", help="use the existing ffmpeg builds as they are")
    parser.add_argument("--compare", type=Path, metavar="RESULTS", help="only apply the thresholds to a results.tsv")
    arguments = parser.parse_args()
    engines = tuple(engine for engine in engines_all if engine in arguments.engines.split(","))
    if "native" not in engines:
        parser.error("--engines must include native, the reference for validation and the ratios")

    if arguments.compare:
        # An earlier run's results: judge them again, rewrite its summary.md and, if asked, the baseline from them.
        rows = read_results(arguments.compare)
        comparison = compare(rows, read_baseline(arguments.baseline), arguments.tolerance, arguments.geomean_tolerance)
        for failure in comparison[3]:
            print(f"REGRESSION: {failure}")
        print(f"host factor {comparison[0]:.3f}; geometric means against the baseline: "
              + ", ".join(f"{engine} {mean:.3f}" for engine, mean in comparison[2].items()))
        metadata_path = arguments.compare.parent / "metadata.json"
        if metadata_path.is_file():
            metadata = json.loads(metadata_path.read_text())
            metadata.update(tolerance=arguments.tolerance, geomean_tolerance=arguments.geomean_tolerance)
            present = tuple(engine for engine in engines_all if any(row["engine"] == engine for row in rows))
            write_summary(arguments.compare.parent / "summary.md", rows, metadata, comparison, present)
            if arguments.update_baseline:
                write_baseline(arguments.baseline, rows, metadata)
                return 0
        return 1 if comparison[3] else 0

    benchmarks = read_set(benchmark_set)
    if arguments.group:
        benchmarks = [benchmark for benchmark in benchmarks if benchmark.group in arguments.group]
    if arguments.only:
        wanted = arguments.only.split(",")
        benchmarks = [benchmark for benchmark in benchmarks
                      if any(benchmark.name == name or name.endswith("*") and benchmark.name.startswith(name[:-1])
                             for name in wanted)]
    if not benchmarks:
        parser.error("no benchmark selected")
    output = (arguments.output or root / "artifacts" / "bench" / datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")).resolve()
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)
    metadata = metadata_for(arguments)
    checks = root / "tests" / "LlvmNet.Checks" / "bin" / "Release" / "net10.0" / "LlvmNet.Checks.dll"
    if subprocess.run(["bash", str(root / "scripts" / "ensure-built.sh")], stdout=subprocess.DEVNULL).returncode:
        log("FAIL: scripts/ensure-built.sh")
        return 2

    log(f"Building {len(benchmarks)} benchmarks ({', '.join(engines)}) in {output}")
    started = time.time()
    suite = suite_path()
    errors = []
    programs = [benchmark for benchmark in benchmarks if benchmark.group != "ffmpeg"]
    with concurrent.futures.ThreadPoolExecutor(arguments.jobs) as pool:
        for benchmark, error in zip(programs, pool.map(lambda item: build_program(item, engines, suite, output), programs)):
            if error:
                errors.append(f"{benchmark.name}: {error}")
    ffmpeg = [benchmark for benchmark in benchmarks if benchmark.group == "ffmpeg"]
    if ffmpeg:
        error = prepare_ffmpeg(ffmpeg, engines, output, not arguments.no_ffmpeg_build)
        if error:
            errors.append(f"ffmpeg: {error}")
    log(f"Built in {time.time() - started:.0f} s")
    for error in errors:
        log(f"FAIL: {error}")
    failed = {error.split(":", 1)[0] for error in errors}
    ready = [benchmark for benchmark in benchmarks
             if benchmark.name not in failed and not (benchmark.group == "ffmpeg" and "ffmpeg" in failed)]

    for benchmark in ready:
        problems = validate(benchmark, engines, output, checks, arguments.timeout)
        for problem in problems:
            log(f"FAIL: {problem}")
        errors += problems
        if not problems:
            log(f"PASS: {benchmark.name} output matches native ({', '.join(engine for engine in engines if engine != 'native')})")
    invalid = {problem.split()[0] for problem in errors}
    ready = [benchmark for benchmark in ready if benchmark.name not in invalid]
    if arguments.validate_only:
        return 1 if errors else 0

    rows = []
    for benchmark in ready:
        try:
            samples = measure(benchmark, engines, output, arguments.repeats, arguments.timeout)
        except (RuntimeError, TimeoutError) as error:
            errors.append(str(error))
            log(f"FAIL: {error}")
            continue
        summaries = {engine: summarize(values) for engine, values in samples.items()}
        native = summaries["native"]["median"]
        for engine, summary in summaries.items():
            rows.append({"benchmark": benchmark.name, "group": benchmark.group, "engine": engine,
                         "runs": summary["runs"], "median_s": f"{summary['median']:.4f}", "min_s": f"{summary['min']:.4f}",
                         "max_s": f"{summary['max']:.4f}", "user_s": f"{summary['user']:.3f}",
                         "system_s": f"{summary['system']:.3f}", "max_rss_kib": summary["rss"],
                         "ratio_to_native": f"{summary['median'] / native:.3f}" if native > 0 else "nan"})
        log(f"{benchmark.name}: " + ", ".join(f"{engine} {summaries[engine]['median']:.3f} s" for engine in engines))

    baseline = read_baseline(arguments.baseline)
    comparison = compare(rows, baseline, arguments.tolerance, arguments.geomean_tolerance)
    if comparison[3] and not arguments.update_baseline:
        # A regression must reproduce: measure the regressed benchmarks again and judge the second measurement.
        suspects = {failure.split()[0] for failure in comparison[3]} - {"jit", "aot"}
        if any(failure.split()[0] in ("jit", "aot") for failure in comparison[3]):
            suspects |= {row["benchmark"] for row in rows}
        log(f"Measuring again to confirm: {', '.join(sorted(suspects))}")
        for benchmark in ready:
            if benchmark.name not in suspects:
                continue
            samples = measure(benchmark, engines, output, arguments.repeats, arguments.timeout)
            for row in rows:
                if row["benchmark"] == benchmark.name:
                    second = summarize(samples[row["engine"]])
                    first = float(row["median_s"])
                    # Keep the faster of the two medians: noise only ever adds time.
                    if second["median"] < first:
                        row.update(median_s=f"{second['median']:.4f}", min_s=f"{second['min']:.4f}",
                                   max_s=f"{second['max']:.4f}", runs=row["runs"] + second["runs"])
            native = next(float(row["median_s"]) for row in rows if row["benchmark"] == benchmark.name and row["engine"] == "native")
            for row in rows:
                if row["benchmark"] == benchmark.name:
                    row["ratio_to_native"] = f"{float(row['median_s']) / native:.3f}"
        comparison = compare(rows, baseline, arguments.tolerance, arguments.geomean_tolerance)

    write_results(output / "results.tsv", rows)
    (output / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    write_summary(output / "summary.md", rows, metadata, comparison, engines)
    if arguments.update_baseline:
        write_baseline(arguments.baseline, rows, metadata)
        log(f"Wrote the baseline {arguments.baseline}")
    print((output / "summary.md").read_text())
    for failure in comparison[3]:
        log(f"REGRESSION: {failure}")
    if errors:
        log(f"{len(errors)} benchmark(s) failed to build, validate or run")
    return 1 if errors or (comparison[3] and not arguments.update_baseline) else 0


if __name__ == "__main__":
    sys.exit(main())
